package io.dockstore.utils.ai;

public interface AIModel {

    /**
     * Submits a prompt to the AI model and returns the response along with usage metadata.
     *
     * @param prompt the text prompt to send to the model
     * @param temperature controls randomness of the response; higher values produce more varied output
     * @param maxResponseTokens the maximum number of tokens to generate in the response
     * @return an {@link AIResponseInfo} containing the response text, truncation status, token counts, cost, and stop reason
     */
    AIResponseInfo submitPrompt(String prompt, double temperature, int maxResponseTokens);

    /**
     * Returns the name of this AI model.
     *
     * @return the model name
     */
    String getModelName();

    /**
     * Returns the cost per input token in USD.
     *
     * @return price per input token
     */
    double getPricePerInputToken();

    /**
     * Returns the cost per output token in USD.
     *
     * @return price per output token
     */
    double getPricePerOutputToken();

    /**
     * Returns the maximum number of tokens this model can process in a single context window,
     * including both input and output tokens.
     *
     * @return the maximum context length in tokens
     */
    int getMaxContextLength();

    /**
     * Calculates the total cost in USD for a request given the number of input and output tokens consumed.
     *
     * @param inputTokens the number of input tokens used
     * @param outputTokens the number of output tokens generated
     * @return the total cost in USD
     */
    default double calculatePrice(long inputTokens, long outputTokens) {
        return (inputTokens * getPricePerInputToken()) + (outputTokens * getPricePerOutputToken());
    }

    /**
     * Estimates the number of tokens in the given text using a character-based heuristic.
     *
     * @param prompt the text to estimate token count for
     * @return the estimated number of tokens
     */
    default int estimateTokens(String prompt) {
        // AWS Bedrock suggests using 6 characters per token as an estimation
        // https://docs.aws.amazon.com/bedrock/latest/userguide/model-customization-prepare.html
        final int estimatedCharactersPerToken = 6;
        return prompt.length() / estimatedCharactersPerToken;
    }

    /**
     * Holds the result of an AI model invocation.
     *
     * @param aiResponse the text generated by the model
     * @param isTruncated whether the response was cut off due to the token limit
     * @param inputTokens the number of input tokens consumed
     * @param outputTokens the number of output tokens generated
     * @param cost the total cost in USD for this request
     * @param stopReason the reason the model stopped generating (e.g., "end_turn", "max_tokens")
     */
    record AIResponseInfo(String aiResponse, boolean isTruncated, long inputTokens, long outputTokens, double cost, String stopReason) {
    }
}
